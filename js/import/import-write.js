/*
 * File: js/import/import-write.js
 * Purpose: Writes the plan as the data file's text (window.PLAN_DATA = {...}), downloads it, and writes the report as plain
 *          text with each region's notes and the check's warnings grouped by kind (D163, D164); docs/ARCHITECTURE.md section 20.
 * Provides: TAP.importWrite (text, jsonPart, download, report)
 * Depends on: js/panel/panel-export.js (download), js/core/content.js (content/text-import.js wording),
 *             js/ui/warning-groups.js (the report's warning groups, at call time)
 * Used by: js/ui/import-panel.js
 * Owner: PLAN stream (#586)
 *
 * text(plan) follows tools/generate-sample-data.js: meta and the lookups pretty-printed, every list one item per line,
 * JSON-compatible literals (double quotes, null, no trailing commas; a non-finite number becomes null), so the data
 * file loads from a <script> tag and JSON.parse(jsonPart(text)) gives the plan back.
 */
(function (TAP) {
  'use strict';

  function say(key, vars) { return TAP.content.text('importPanel.check.report.' + key, vars); }
  function isObj(v) { return !!v && typeof v === 'object' && !Array.isArray(v); }

  /* ---------- the data file ---------- */

  function inline(v) {
    if (Array.isArray(v)) return '[' + v.map(inline).join(', ') + ']';
    if (isObj(v)) {
      return '{' + Object.keys(v).filter(function (k) { return v[k] !== undefined; })
        .map(function (k) { return JSON.stringify(k) + ': ' + inline(v[k]); }).join(', ') + '}';
    }
    if (typeof v === 'number') return isFinite(v) ? JSON.stringify(v) : 'null';
    if (v === undefined) return 'null';
    return JSON.stringify(v);
  }

  // A list one item per line; the closing bracket one space in from the items
  function list(items, indent) {
    if (!items.length) return '[]';
    return '[\n' + items.map(function (x) { return indent + inline(x); }).join(',\n') + '\n' + indent.slice(1) + ']';
  }

  // An object whose lists are written one item per line (customerGrowth, baseYear, extra); the rest inline
  function withLists(v, indent) {
    return '{' + Object.keys(v).filter(function (k) { return v[k] !== undefined; }).map(function (k) {
      return JSON.stringify(k) + ': ' + (Array.isArray(v[k]) ? list(v[k], indent) : inline(v[k]));
    }).join(', ') + '}';
  }

  function metaText(m) {
    var rest = Object.assign({}, m);
    delete rest.extraSections;
    if (!Array.isArray(m.extraSections)) return inline(rest);
    return inline(rest).slice(0, -1) + ', "extraSections": ' + list(m.extraSections, '  ') + '}';
  }

  function lookupsText(lk) {
    return '{\n' + Object.keys(lk).map(function (k) {
      var v = lk[k], body;
      if (Array.isArray(v)) body = list(v, '  ');
      else if (isObj(v)) body = '{\n' + Object.keys(v).map(function (s) { return '  ' + JSON.stringify(s) + ': ' + inline(v[s]); }).join(',\n') + '\n }';
      else body = inline(v);
      return ' ' + JSON.stringify(k) + ': ' + body;
    }).join(',\n') + '\n}';
  }

  function regionText(r) {
    var head = inline({ id: r.id, name: r.name, source: r.source }).slice(0, -1), rest = [];
    Object.keys(r).forEach(function (k) {
      if (k === 'id' || k === 'name' || k === 'source' || r[k] === undefined) return;
      var v = r[k], body;
      if (Array.isArray(v)) body = list(v, '   ');
      else if (isObj(v)) body = withLists(v, '   ');
      else body = inline(v);
      rest.push('  ' + JSON.stringify(k) + ': ' + body);
    });
    return ' ' + head + (rest.length ? ',\n' + rest.join(',\n') : '') + '\n }';
  }

  function header(meta) {
    return ['/*', ' * File: data/plan-data.js',
      ' * Purpose: The plan data the app shows, every region\'s territory account plan (Data Contract v' + (meta.schemaVersion || '') + ', docs/DATA-CONTRACT.md).',
      ' * Provides: window.PLAN_DATA',
      ' * Depends on: nothing',
      ' * Used by: index.html',
      ' *',
      ' * Generated by the in-app import on ' + meta.generatedAt + ' from the template mapping ' + meta.templateVersion + '. Do not edit by hand:',
      ' * run the import again instead. Money is in thousands of ' + meta.currency + '; rates are decimals.',
      ' */'].join('\n');
  }

  function text(plan) {
    var meta = plan.meta || {}, body = [
      '"meta": ' + metaText(meta) + ',',
      '"lookups": ' + lookupsText(plan.lookups || {}) + ',',
      '"regions": [\n' + (plan.regions || []).map(regionText).join(',\n') + '\n]'
    ];
    return [header(meta), 'window.PLAN_DATA = {', body.join('\n'), '};', ''].join('\n');
  }

  // The object literal between "window.PLAN_DATA =" and the final ";", for JSON.parse
  function jsonPart(s) {
    var at = s.indexOf('window.PLAN_DATA ='), start = s.indexOf('{', at < 0 ? 0 : at), end = s.lastIndexOf('};');
    if (start < 0 || end < start) return '';
    return s.slice(start, end + 1);
  }

  function download(plan, name) {
    var blob = new Blob([text(plan)], { type: 'text/javascript' }), url = URL.createObjectURL(blob);
    TAP.panelExport.download(url, name || 'plan-data.js');
    setTimeout(function () { URL.revokeObjectURL(url); }, 0);
    return url;
  }

  /* ---------- the plain-text report ---------- */

  function where(x) {
    if (x.sheet && x.cell) return say('where', { sheet: x.sheet, cell: x.cell });
    if (x.sheet) return say('whereSheet', { sheet: x.sheet });
    return say('whereNone');
  }

  // A kind group as text: the title with its count, the intro once, then each plain row (where, found, expected, the
  // address) over its technical message, which is what gets pasted into the approved tool (D163, D164)
  function kindLines(k, prefix) {
    var W = TAP.warningGroups, out = [say(prefix + 'Kind', { title: k.title, n: k.items.length })];
    if (k.intro) out.push(say(prefix + 'Intro', { intro: k.intro }));
    k.items.forEach(function (it) { out.push(say(prefix + 'Plain', { line: W.row(it) }), say(prefix + 'Tech', { message: it.tech })); });
    return out;
  }

  // One region: its state and facts, its errors, then its notes grouped by kind. Flat when the component is not loaded.
  function regionLines(r, result) {
    var W = TAP.warningGroups, out = [say('region', { name: r.name || r.fileName, status: say(r.ok ? 'imported' : 'leftOut') })];
    var src = r.region && r.region.source, parts = Object.keys(r.parts || {}).map(function (k) {
      return say('part', { section: TAP.content.text('importPanel.check.sections.' + k), state: say('parts.' + r.parts[k]) });
    });
    out.push(say('facts', { file: r.fileName, date: src && src.fileModified ? src.fileModified : say('noDate'), parts: parts.join(', ') }));
    (r.errors || []).forEach(function (e) { out.push(say('error', { where: where(e), message: e.message })); });
    if (!W) return out.concat((r.notes || []).map(function (n) { return say('note', { where: where(n), message: n.message }); }));
    W.kindGroups(W.fromImport(r.notes || [], r.name)).forEach(function (k) { out = out.concat(kindLines(k, 'note')); });
    return out;
  }

  // The check's warnings by workbook, then kind (US-1.8.8), the ids labelled with the plan's lookups
  function warningLines(result) {
    var W = TAP.warningGroups, out = [], files = {};
    if (!W) return result.check.warnings.map(function (w) { return say('checkLine', { message: w.message }); });
    (result.regions || []).forEach(function (r) { if (r.name) files[r.name] = r.fileName || null; });
    W.groups(result.check.warnings, files, { lookups: result.plan ? result.plan.lookups : null }).forEach(function (g) {
      out.push(say('checkBook', { label: g.label, n: g.n }));
      g.kinds.forEach(function (k) { out = out.concat(kindLines(k, 'check')); });
    });
    return out;
  }

  function report(result) {
    var out = [];
    (result.regions || []).forEach(function (r) { out = out.concat(regionLines(r, result)); });
    if (!(result.regions || []).length) out.push(say('none'));
    (result.missing || []).forEach(function (m) { out.push(say('missing', { name: m.name, id: m.id })); });
    (result.mapProblems || []).forEach(function (p) { out.push(say('mapProblem', { message: p })); });
    if (result.check) {
      out.push(say('checkErrors', { n: result.check.errors.length }));
      result.check.errors.forEach(function (e) { out.push(say('checkLine', { message: e.message })); });
      out.push(say('checkWarnings', { n: result.check.warnings.length }));
      out = out.concat(warningLines(result));
    }
    return out.join('\n') + '\n';
  }

  TAP.importWrite = { text: text, jsonPart: jsonPart, download: download, report: report };
})(window.TAP);
