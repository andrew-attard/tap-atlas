/*
 * File: tools/build-auto-cases.js
 * Purpose: Reads the Test Plan and writes the list of automated test cases the test page must cover
 *          (TPV-TC-219: every automated case has a matching test). Development only.
 * Provides: a command: node tools/build-auto-cases.js "<path to Test Plan.md>"
 * Depends on: Node 18+, nothing else
 * Used by: the lead, whenever the Test Plan's automated cases change; writes tests/auto-cases.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  process.stderr.write('Usage: node tools/build-auto-cases.js "<path to Test Plan.md>"\n');
  process.exit(2);
}

const field = function (line, name) {
  const m = line.match(new RegExp('\\(' + name + ':: ([^)]+)\\)'));
  return m ? m[1].trim() : null;
};

const cases = fs.readFileSync(src, 'utf8').split(/\r?\n/)
  .filter(function (l) { return /^- \[[ x]\] \(tc:: TPV-TC-\d+\)/.test(l) && field(l, 'type') === 'auto'; })
  .map(function (l) {
    const text = l.replace(/^- \[[ x]\] /, '').replace(/\([a-z]+:: [^)]+\)\s*/g, '').replace(/\s*\^TPV-TC-\d+\s*$/, '').trim();
    return { id: field(l, 'tc'), story: field(l, 'story'), smoke: field(l, 'smoke') === 'yes', text: text };
  });

const out = '/*\n * File: tests/auto-cases.js\n' +
  ' * Purpose: The automated test cases listed in the Test Plan, so the test page can show any without a test as pending.\n' +
  ' * Provides: window.TAP_AUTO_CASES\n * Depends on: nothing (generated by tools/build-auto-cases.js; do not edit by hand)\n' +
  ' * Used by: tests/harness.js (pending list), tests/test-meta.js\n */\n' +
  'window.TAP_AUTO_CASES = [\n' + cases.map(function (c) { return '  ' + JSON.stringify(c); }).join(',\n') + '\n];\n';

fs.writeFileSync(path.join(__dirname, '..', 'tests', 'auto-cases.js'), out);
process.stdout.write('Wrote ' + cases.length + ' automated cases to tests/auto-cases.js\n');
